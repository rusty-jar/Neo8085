_TOKEN_RE = re.compile(
    r"\s*(?:"
    r"(?P<num>[0-9][0-9A-Z]*)"
    r"|(?P<name>[A-Z?@_][A-Z0-9?@_]*)"
    r"|(?P<str>'(?:[^']|'')*')"
    r"|(?P<op><<|>>|[-+*/()&|^~$])"
    r")"
)
_BLOCK_DIRECTIVES = ("MACRO", "REPT", "IRP", "IRPC")
