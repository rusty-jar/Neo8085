"""
Assembly listing (opcode listing) in the style of the Intel 8080/8085
assembler: location counter, object code, line number and source statement
for every line, followed by a symbol table and a summary.

    LOC   OBJ          LINE    SOURCE STATEMENT
    2000  21 50 20        4    START:  LXI H, NUM1

Lines generated by macro, REPT, IRP and IRPC expansions are listed after the
statement that produced them, marked with "+". Data longer than four bytes
continues on extra lines.
"""

import re

BYTES_PER_ROW = 4
_OBJ_WIDTH = BYTES_PER_ROW * 3 - 1
# Column where the source statement starts (LOC, OBJ, LINE and the "+" marker before it)
SOURCE_COLUMN = 5 + 1 + _OBJ_WIDTH + 1 + 5 + 3
_EQU_RE = re.compile(r"^\s*([A-Za-z?@][\w?@]*)\s*:?\s+EQU\b", re.IGNORECASE)
_BLOCK_OPEN_RE = re.compile(r"(^|\s)(MACRO|REPT|IRP|IRPC)(\s|$)", re.IGNORECASE)
_DEFERRED_RE = re.compile(r"(^|\s)(REPT|IRP|IRPC)(\s|$)", re.IGNORECASE)
_ENDM_RE = re.compile(r"(^|\s)ENDM(\s|$)", re.IGNORECASE)


def _code_part(line):
    """The line without its comment (a ';' outside quotes starts the comment)."""
    quote = None
    for index, ch in enumerate(line):
        if quote:
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
        elif ch == ";":
            return line[:index]
    return line


def _block_ends(lines):
    """
    For every REPT/IRP/IRPC line, the line number of its matching ENDM, so the
    expansion can be listed after the block (as the Intel assembler does).
    """
    ends = {}
    stack = []
    for number, line in enumerate(lines, 1):
        code = _code_part(line)
        if _BLOCK_OPEN_RE.search(code):
            stack.append((number, bool(_DEFERRED_RE.search(code))))
        elif _ENDM_RE.search(code) and stack:
            start, deferred = stack.pop()
            if deferred and not stack:  # nested blocks expand with the outermost one
                ends[start] = number
    return ends


def _hex_bytes(data):
    return " ".join(f"{byte:02X}" for byte in data)


def _row(location, obj, line_number, marker, text):
    loc = f"{location:04X}" if isinstance(location, int) else (location or "")
    number = "" if line_number is None else str(line_number)
    return f"{loc:<5} {obj:<{_OBJ_WIDTH}} {number:>5} {marker} {text}".rstrip()


def _object_rows(address, data, line_number, marker, text):
    """One or more listing rows for a statement's bytes (4 bytes per row)."""
    rows = [_row(address, _hex_bytes(data[:BYTES_PER_ROW]), line_number, marker, text)]
    for offset in range(BYTES_PER_ROW, len(data), BYTES_PER_ROW):
        rows.append(_row((address + offset) & 0xFFFF, _hex_bytes(data[offset:offset + BYTES_PER_ROW]),
                         None, " ", ""))
    return rows


def _record_rows(record, line_number, source_text):
    _, address, data, kind, expanded, value = record
    marker = "+" if expanded is not None else " "
    text = expanded if expanded is not None else source_text
    if kind == "set":
        return [_row(None, f"= {value:04X}", line_number, marker, text)]
    if kind == "ds":
        return [_row(address, f"({value} bytes)" if value != 1 else "(1 byte)", line_number, marker, text)]
    if not data:
        return [_row(address, "", line_number, marker, text)]
    return _object_rows(address, data, line_number, marker, text)


def build_listing(output, title="Untitled"):
    """
    Builds the listing text for an AssemblyOutput (from Assembler8085.assemble).
    """
    lines = [line.expandtabs(8).rstrip() for line in output.source_lines]
    by_line = {}
    for record in output.listing:
        by_line.setdefault(record[0], []).append(record)
    block_ends = _block_ends(lines)
    deferred_until = {}
    for start, end in block_ends.items():
        deferred_until.setdefault(end, []).append(start)

    rows = [
        f"Neo8085 8085 Assembler - Listing of {title}",
        "",
        f"{'LOC':<5} {'OBJ':<{_OBJ_WIDTH}} {'LINE':>5}   SOURCE STATEMENT",
        "",
    ]
    for number, text in enumerate(lines, 1):
        records = by_line.get(number, []) if number not in block_ends else []
        source_records = [r for r in records if r[4] is None]
        expansion = [r for r in records if r[4] is not None]

        if source_records:
            rows.extend(_record_rows(source_records[0], number, text))
            for record in source_records[1:]:
                rows.extend(_record_rows(record, None, ""))
        else:
            equ = _EQU_RE.match(_code_part(text))
            name = equ.group(1).upper() if equ else None
            if name is not None and name in output.symbols:
                rows.append(_row(None, f"= {output.symbols[name]:04X}", number, " ", text))
            else:
                rows.append(_row(None, "", number, " ", text))

        for record in expansion:
            rows.extend(_record_rows(record, None, ""))
        # Expansions of REPT/IRP/IRPC blocks that end on this line
        for start in deferred_until.get(number, []):
            for record in by_line.get(start, []):
                rows.extend(_record_rows(record, None, ""))

    rows += ["", ""] + symbol_table(output) + [""] + summary(output)
    return "\n".join(rows) + "\n"


def symbol_table(output):
    """Labels and symbols sorted by name, three per row."""
    entries = {}
    for name, value in output.labels.items():
        entries[name] = (value, "L")
    for name, value in output.symbols.items():
        if isinstance(value, int):
            entries.setdefault(name, (value, "S"))
    rows = ["SYMBOL TABLE   (L = label, S = EQU/SET symbol)", ""]
    if not entries:
        return rows + ["  (no symbols)"]
    cells = [f"{name[:16]:<16} {kind} {value & 0xFFFF:04X}" for name, (value, kind) in sorted(entries.items())]
    for index in range(0, len(cells), 3):
        rows.append("  " + "    ".join(cells[index:index + 3]))
    return rows


def _ranges(addresses):
    ranges = []
    for address in addresses:
        if ranges and address == ranges[-1][1] + 1:
            ranges[-1][1] = address
        else:
            ranges.append([address, address])
    return ranges


def summary(output):
    code = sum(len(r[2]) for r in output.listing if r[3] == "instr")
    data = sum(len(r[2]) for r in output.listing if r[3] in ("db", "dw"))
    reserved = sum(r[5] for r in output.listing if r[3] == "ds")
    instructions = sum(1 for r in output.listing if r[3] == "instr")
    ranges = ", ".join(f"{start:04X}H-{end:04X}H" for start, end in _ranges(output.object_addresses))
    return [
        f"Start address: {output.starting_address:04X}H",
        f"Instructions:  {instructions} ({code} bytes of code)",
        f"Data:          {data} bytes (DB/DW), {reserved} bytes reserved (DS)",
        f"Object code:   {ranges or 'none'}",
    ]
