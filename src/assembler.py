"""
Two-pass 8085 assembler compatible with the Intel 8080/8085 assembly language
(Intel 8080/8085 Assembly Language Programming Manual).

Source format:
    [LABEL:] MNEMONIC [operand[, operand...]] [; comment]
    NAME EQU expression          NAME SET expression
    NAME MACRO [param, ...] ... ENDM

Constants:  decimal (10, 10D), hexadecimal (0FFH, must start with a digit),
            binary (1010B), octal (17O, 17Q), characters ('A', 'AB'), $ = location counter
Operators (Intel precedence, highest first):
    ( )
    NUL, HIGH, LOW
    *  /  MOD  SHL  SHR
    +  -  (unary and binary)
    EQ  NE  LT  LE  GT  GE   (true = 0FFFFH, false = 0)
    NOT
    AND
    OR  XOR
  All arithmetic is unsigned 16-bit. The operators & | ^ ~ << >> are accepted
  as synonyms for AND OR XOR NOT SHL SHR.
Directives: ORG EQU SET DB DW DS END IF ELSE ENDIF MACRO ENDM LOCAL EXITM REPT IRP IRPC

Compatibility extensions kept from earlier Neo8085 versions:
    NAME: EQU value  (colon after an EQU/SET/MACRO name), '_' in names.
"""

import re


class AssemblyOutput:
    """Result of Assembler8085.assemble(): the memory image, symbols and debug metadata."""

    def __init__(self):
        self.memory = bytearray(0x10000)  # 64KB memory space
        self.parsed_program = []
        self.line_to_address_map = {}
        self.address_to_line_map = {}
        self.labels = {}
        self.symbols = {}  # EQU symbol definitions (and final SET values)
        self.program_end_address = 0
        self.program_memory_range = set()  # Code addresses (protected)
        self.data_memory_range = set()  # DS/DB/DW addresses (writable)
        self.starting_address = 0x0000
        self.source_lines = []  # The assembled source, one entry per line
        # Listing records in assembly order: (line number, address, bytes,
        # kind, expanded text, value). Expanded text is the statement as
        # generated by a macro/REPT/IRP expansion (None for source lines);
        # value is the value of a SET statement or the size of a DS area.
        self.listing = []

    @property
    def object_addresses(self):
        """Addresses that received code or data bytes (DS areas excluded), in order."""
        addresses = set()
        for _, address, data, _, _, _ in self.listing:
            addresses.update((address + offset) & 0xFFFF for offset in range(len(data)))
        return sorted(addresses)


class AssemblerError(Exception):
    """Error in one source statement (line number is added by the caller)."""


class UndefinedSymbolError(AssemblerError):
    def __init__(self, name):
        hint = ""
        if re.fullmatch(r"[A-F][0-9A-F]*H", name):
            hint = f" (hexadecimal numbers must start with a digit, e.g. 0{name})"
        super().__init__(f"Undefined symbol: {name}{hint}")
        self.name = name


