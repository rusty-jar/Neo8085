def _normalize(line):
    """Removes the comment and upper-cases everything outside quoted strings."""
    out = []
    in_string = False
    i = 0
    while i < len(line):
        ch = line[i]
        if in_string:
            out.append(ch)
            if ch == "'":
                if i + 1 < len(line) and line[i + 1] == "'":
                    out.append("'")
                    i += 2
                    continue
                in_string = False
        elif ch == ";":
            break
        elif ch == "'":
            in_string = True
            out.append(ch)
        else:
            out.append(ch.upper())
        i += 1
    if in_string:
        raise AssemblerError("Unterminated string constant")
    return "".join(out).strip()


def _split_operands(text, angle_brackets=False):
    """Splits an operand field on commas outside strings, parentheses and <...>."""
    if not text.strip():
        return []
    parts = []
    current = []
    in_string = False
    depth = 0
    for ch in text:
        if in_string:
            current.append(ch)
            if ch == "'":
                in_string = False
            continue
        if ch == "'":
            in_string = True
        elif ch == "(" or (angle_brackets and ch == "<"):
            depth += 1
        elif ch == ")" or (angle_brackets and ch == ">"):
            depth -= 1
        elif ch == "," and depth == 0:
            parts.append("".join(current).strip())
            current = []
            continue
        current.append(ch)
    parts.append("".join(current).strip())
    return parts


def _strip_angle_brackets(text):
    text = text.strip()
    if text.startswith("<") and text.endswith(">"):
        return text[1:-1]
    return text


def _string_value(token):
    return token[1:-1].replace("''", "'")


def _peek_directive(code):
    """Returns MACRO/REPT/IRP/IRPC/ENDM/IF/ELSE/ENDIF/END if the line is one, else None."""
    rest = re.sub(r"^[^\s':]*:\s*", "", code)
    words = rest.split()
    if not words:
        return None
    if words[0] in ("REPT", "IRP", "IRPC", "ENDM", "IF", "ELSE", "ENDIF", "END", "MACRO"):
        return words[0]
    if len(words) > 1 and words[1] == "MACRO":
        return "MACRO"
    return None


class _Macro:
    def __init__(self, name, params, body):
        self.name = name
        self.params = params
        self.body = body  # list of normalized code lines


class _Frame:
    """A source of lines: the program itself or one macro/REPT expansion."""

    def __init__(self, lines, kind, name=None, cond_depth=0):
        self.lines = lines  # list of (line_num, text)
        self.index = 0
        self.kind = kind  # "source", "macro" or "rept"
        self.name = name
        self.cond_depth = cond_depth


class _Statement:
    __slots__ = ("kind", "line_num", "context", "address", "mnemonic", "operands", "name", "size")

    def __init__(self, kind, line_num, context, address, mnemonic=None, operands=(), name=None, size=0):
        self.kind = kind
        self.line_num = line_num
        self.context = context
        self.address = address
        self.mnemonic = mnemonic
        self.operands = operands
        self.name = name
        self.size = size


class Assembler8085:
    """
    Intel-compatible 8085 assembler producing machine code and debug metadata.
    """

    def __init__(self):
        self.valid_opcodes = list(INSTRUCTION_SIZES) + list(DIRECTIVES)
        self.valid_registers = list(REGISTERS)
        self.valid_register_pairs = list(REGISTER_PAIRS)

    # ------------------------------------------------------------------
    # Public entry point
    # ------------------------------------------------------------------

    def assemble(self, code):
        """
        Assembles a program given as a list of source lines.

        Returns an AssemblyOutput. Raises SyntaxError, with the line number in
        the message, for the first error found.
        """
        self._output = AssemblyOutput()
        self._set_values = {}
        self._pending_equs = {}  # name -> (expression, address or None, line_num)
        self._equ_defined = set()
        self._resolving = set()
        self._macros = {}
        self._local_counter = 0

        self._output.source_lines = list(code)
        source = list(enumerate(code, 1))
        self._prescan_equs(source)
        statements = self._pass1(source)
        self._resolve_pending_equs()
        self._pass2(statements)
        return self._output

    # ------------------------------------------------------------------
    # Expression evaluation
    # ------------------------------------------------------------------

    def _evaluate(self, text, address, allow_registers=False):
        """Evaluates an Intel expression to an unsigned 16-bit value."""
        tokens = self._tokenize_expression(text)
        if not tokens:
            raise AssemblerError("Missing expression")
        parser = _ExpressionParser(self, tokens, address, allow_registers, text)
        return parser.parse()

    def _tokenize_expression(self, text):
        tokens = []
        position = 0
        text = text.rstrip()
        while position < len(text):
            match = _TOKEN_RE.match(text, position)
            if not match or match.end() == position:
                raise AssemblerError(f"Invalid character in expression: {text[position:].strip()}")
            position = match.end()
            if match.group("num") is not None:
                tokens.append(("num", self._parse_number(match.group("num"))))
            elif match.group("name") is not None:
                name = match.group("name")
                tokens.append(("op" if name in OPERATOR_WORDS else "name", name))
            elif match.group("str") is not None:
                tokens.append(("str", _string_value(match.group("str"))))
            else:
                tokens.append(("op", match.group("op")))
        return tokens

    def _parse_number(self, text):
        """Parses an Intel numeric constant (suffix H, B, O, Q, D or none)."""
        text = text.strip().upper()
        suffix = text[-1:]
        bases = {"H": 16, "B": 2, "O": 8, "Q": 8, "D": 10}
        if suffix in bases and len(text) > 1:
            base, digits = bases[suffix], text[:-1]
        else:
            base, digits = 10, text
        allowed = "0123456789ABCDEF"[:base]
        if not digits or digits[0] not in "0123456789" or any(c not in allowed for c in digits):
            raise AssemblerError(f"Invalid number: {text}")
        value = int(digits, base)
        if value > 0xFFFF:
            raise AssemblerError(f"Number out of range (more than 16 bits): {text}")
        return value

    def _lookup(self, name, allow_registers):
        if name in self._set_values:
            return self._set_values[name]
        output = self._output
        if name in output.symbols:
            return output.symbols[name]
        if name in output.labels:
            return output.labels[name]
        if name in REGISTER_VALUES:
            if allow_registers:
                return REGISTER_VALUES[name]
            raise AssemblerError(f"Register name {name} cannot be used as a value here")
        if name in self._pending_equs and name not in self._resolving:
            expression, address, line_num = self._pending_equs[name]
            self._resolving.add(name)
            try:
                value = self._evaluate(expression, address, allow_registers=True)
            finally:
                self._resolving.discard(name)
            output.symbols[name] = value
            del self._pending_equs[name]
            return value
        raise UndefinedSymbolError(name)

    # ------------------------------------------------------------------
    # Line parsing
    # ------------------------------------------------------------------

    def _parse_fields(self, code):
        """Returns (label, name, mnemonic, operand_text) for a normalized line."""
        label = None
        match = _LABEL_PREFIX_RE.match(code)
        if match:
            label, rest = match.group(1), match.group(2).strip()
            if _LABEL_PREFIX_RE.match(rest):
                raise AssemblerError(f"Invalid label format: {code.split()[0]}")
        else:
            first = code.split(None, 1)[0]
            if ":" in first and "'" not in first:
                raise AssemblerError(f"Invalid label format: {first}")
            rest = code

        if not rest:
            return label, None, None, ""

        parts = rest.split(None, 1)
        mnemonic = parts[0]
        operand_text = parts[1].strip() if len(parts) > 1 else ""
        name = None

        if label is None and operand_text:
            second = operand_text.split(None, 1)
            if second[0] in ("EQU", "SET", "MACRO") and _NAME_RE.fullmatch(mnemonic):
                name = mnemonic
                mnemonic = second[0]
                operand_text = second[1].strip() if len(second) > 1 else ""

        if label is not None and mnemonic in ("EQU", "SET", "MACRO"):
            name, label = label, None

        return label, name, mnemonic, operand_text

    def _check_operand_count(self, mnemonic, operands):
        count = len(operands)
        if any(not operand for operand in operands):
            raise AssemblerError("Missing operand")
        if mnemonic in _TWO_OPERANDS or mnemonic in ("IRP", "IRPC"):
            expected = 2
        elif mnemonic in _ZERO_OPERANDS or mnemonic in ("ELSE", "ENDIF", "ENDM", "EXITM"):
            expected = 0
        elif mnemonic == "END":
            if count > 1:
                raise AssemblerError("END takes at most one operand")
            return
        elif mnemonic in ("DB", "DW", "LOCAL"):
            if count == 0:
                raise AssemblerError(f"{mnemonic} expects at least 1 operand")
            return
        else:
            expected = 1
        if count != expected:
            noun = "operand" if expected == 1 else "operands"
            raise AssemblerError(f"{mnemonic} expects {expected} {noun}, got {count}")

    def _check_new_name(self, name, kind="label"):
        if not _NAME_RE.fullmatch(name):
            raise AssemblerError(f"Invalid {kind} name: {name}")
        if name in RESERVED_WORDS:
            raise AssemblerError(f"{name} is a reserved word and cannot be used as a {kind}")
        output = self._output
        if (
            name in output.labels
            or name in self._equ_defined
            or name in self._macros
            or (kind != "SET symbol" and name in self._set_values)
        ):
            word = "label" if kind == "label" else "symbol"
            raise AssemblerError(f"Duplicate {word}: {name}")

    # ------------------------------------------------------------------
    # EQU pre-scan / resolution
    # ------------------------------------------------------------------

    def _prescan_equs(self, source):
        """
        Registers top-level EQU definitions before pass 1 so that DS, ORG and
        other EQUs may refer to constants defined further down in the program.
        """
        block_depth = 0
        cond_depth = 0
        for line_num, line in source:
            try:
                code = _normalize(line)
            except AssemblerError:
                continue
            if not code:
                continue
            directive = _peek_directive(code)
            if directive in _BLOCK_DIRECTIVES:
                block_depth += 1
                continue
            if directive == "ENDM":
                block_depth = max(0, block_depth - 1)
                continue
            if directive == "IF":
                cond_depth += 1
                continue
            if directive == "ENDIF":
                cond_depth = max(0, cond_depth - 1)
                continue
            if directive == "END" and block_depth == 0 and cond_depth == 0:
                break
            if block_depth or cond_depth:
                continue
            try:
                _, name, mnemonic, operand_text = self._parse_fields(code)
            except AssemblerError:
                continue
            if mnemonic == "EQU" and name and operand_text and name not in self._pending_equs:
                self._pending_equs[name] = (operand_text, None, line_num)

    def _resolve_pending_equs(self):
        unresolved = []
        for name in list(self._pending_equs):
            if name not in self._pending_equs:
                continue  # resolved while resolving another symbol
            if name not in self._equ_defined:
                del self._pending_equs[name]  # pre-scan hint for a skipped definition
                continue
            line_num = self._pending_equs[name][2]
            try:
                self._lookup(name, allow_registers=True)
            except UndefinedSymbolError as e:
                unresolved.append((line_num, name, e.name))
            except AssemblerError as e:
                raise SyntaxError(f"Line {line_num}: {e}")
        if unresolved:
            line_num, name, missing = unresolved[0]
            names = ", ".join(n for _, n, _ in unresolved)
            raise SyntaxError(
                f"Line {line_num}: Could not resolve EQU symbols: {names} (undefined symbol: {missing})"
            )

    # ------------------------------------------------------------------
    # Pass 1: macro expansion, conditional assembly, addresses and labels
    # ------------------------------------------------------------------

    def _pass1(self, source):
        output = self._output
        address = 0
        first_org_seen = False
        statements = []
        stack = [_Frame(source, "source")]
        conditions = []  # [active, branch_taken, parent_active, line_num]
        collecting = None  # dict describing a MACRO/REPT/IRP/IRPC body being read

        while stack:
            frame = stack[-1]
            if frame.index >= len(frame.lines):
                stack.pop()
                if frame.kind != "source" and len(conditions) != frame.cond_depth:
                    raise SyntaxError(
                        f"Line {frame.lines[-1][0] if frame.lines else 0}: "
                        f"IF without ENDIF in expansion of {frame.name}"
                    )
                continue

            line_num, text = frame.lines[frame.index]
            frame.index += 1
            context = f" (in {frame.name})" if frame.kind != "source" else ""

            try:
                code = _normalize(text) if frame.kind == "source" else text
                if not code:
                    continue

                # Collecting the body of a MACRO / REPT / IRP / IRPC block
                if collecting is not None:
                    directive = _peek_directive(code)
                    if directive in _BLOCK_DIRECTIVES:
                        collecting["depth"] += 1
                    elif directive == "ENDM":
                        collecting["depth"] -= 1
                        if collecting["depth"] == 0:
                            block, collecting = collecting, None
                            if block["active"]:
                                new_frame = self._finish_block(block, conditions, stack)
                                if new_frame is not None:
                                    stack.append(new_frame)
                            continue
                    collecting["body"].append(code)
                    continue

                active = all(entry[0] for entry in conditions)

                # Inside a false IF branch only track nesting
                if not active:
                    directive = _peek_directive(code)
                    if directive == "IF":
                        conditions.append([False, True, False, line_num, False])
                    elif directive in ("ELSE", "ENDIF"):
                        self._conditional(directive, None, address, conditions, line_num)
                    elif directive in _BLOCK_DIRECTIVES:
                        collecting = {"kind": directive, "depth": 1, "body": [], "active": False}
                    continue

                label, name, mnemonic, operand_text = self._parse_fields(code)

                if mnemonic in ("IF", "ELSE", "ENDIF"):
                    if label:
                        raise AssemblerError(f"A label is not allowed on {mnemonic}")
                    self._conditional(mnemonic, operand_text, address, conditions, line_num)
                    continue

                if label:
                    self._check_new_name(label)
                    output.labels[label] = address

                if mnemonic is None:
                    continue

                is_macro_call = mnemonic in self._macros
                if not is_macro_call and mnemonic not in INSTRUCTION_SIZES and mnemonic not in DIRECTIVES:
                    raise AssemblerError(f"Unknown instruction: {mnemonic}")

                if mnemonic in ("MACRO", "IRP"):
                    operands = _split_operands(operand_text, angle_brackets=True)
                elif is_macro_call:
                    operands = [_strip_angle_brackets(a) for a in _split_operands(operand_text, angle_brackets=True)]
                else:
                    operands = _split_operands(operand_text)
                if mnemonic not in ("MACRO",) and not is_macro_call:
                    self._check_operand_count(mnemonic, operands)

                if mnemonic in ("EQU", "SET", "MACRO") and not name:
                    raise AssemblerError(f"{mnemonic} requires a name")

                # ---- block directives ----
                if mnemonic == "MACRO":
                    self._check_new_name(name, "macro")
                    params = [p for p in operands if p]
                    for param in params:
                        if not _NAME_RE.fullmatch(param):
                            raise AssemblerError(f"Invalid macro parameter: {param}")
                    collecting = {"kind": "MACRO", "depth": 1, "body": [], "active": True,
                                  "name": name, "params": params, "line": line_num}
                    continue

                if mnemonic == "REPT":
                    count = self._evaluate(operands[0], address)
                    collecting = {"kind": "REPT", "depth": 1, "body": [], "active": True,
                                  "count": count, "line": line_num, "context": context}
                    continue

                if mnemonic in ("IRP", "IRPC"):
                    param = operands[0]
                    if not _NAME_RE.fullmatch(param):
                        raise AssemblerError(f"Invalid {mnemonic} parameter: {param}")
                    if mnemonic == "IRP":
                        values = [_strip_angle_brackets(v) for v in _split_operands(_strip_angle_brackets(operands[1]), True)]
                    else:
                        values = list(_strip_angle_brackets(operands[1]))
                    collecting = {"kind": mnemonic, "depth": 1, "body": [], "active": True,
                                  "param": param, "values": values, "line": line_num, "context": context}
                    continue

                if mnemonic == "ENDM":
                    raise AssemblerError("ENDM without MACRO, REPT, IRP or IRPC")

                if mnemonic == "EXITM":
                    if frame.kind == "source":
                        raise AssemblerError("EXITM outside a macro")
                    exited = stack.pop()  # leave the innermost expansion
                    del conditions[exited.cond_depth:]
                    continue

                if mnemonic == "LOCAL":
                    raise AssemblerError("LOCAL must directly follow the MACRO line")

                if is_macro_call:
                    depth = sum(1 for f in stack if f.kind != "source")
                    if depth >= _MAX_EXPANSION_DEPTH:
                        raise AssemblerError("Macro expansion nested too deeply (recursive macro?)")
                    stack.append(self._expand_macro(self._macros[mnemonic], operands, line_num, len(conditions)))
                    continue

                # ---- symbol definitions ----
                if mnemonic == "EQU":
                    self._check_new_name(name, "symbol")
                    self._equ_defined.add(name)
                    self._pending_equs.pop(name, None)
                    output.symbols.pop(name, None)  # value from pre-scan, recomputed with $
                    try:
                        output.symbols[name] = self._evaluate(operands[0], address, allow_registers=True)
                    except UndefinedSymbolError:
                        self._pending_equs[name] = (operands[0], address, line_num)
                    continue

                if mnemonic == "SET":
                    if name in output.labels or name in self._equ_defined or name in self._macros:
                        raise AssemblerError(f"Duplicate symbol: {name}")
                    self._check_new_name(name, "SET symbol")
                    self._set_values[name] = self._evaluate(operands[0], address, allow_registers=True)
                    statements.append(_Statement("set", line_num, context, address, mnemonic, operands, name))
                    continue

                # ---- location counter ----
                if mnemonic == "END":
                    statements.append(_Statement("end", line_num, context, address, mnemonic, operands))
                    break

                if mnemonic == "ORG":
                    address = self._evaluate(operands[0], address)
                    if not first_org_seen:
                        output.starting_address = address
                        first_org_seen = True
                    continue

                if mnemonic == "DS":
                    size = self._evaluate(operands[0], address)
                    if address + size > 0x10000:
                        raise AssemblerError(f"Invalid DS size: {operands[0]} (exceeds 64KB)")
                    statements.append(_Statement("ds", line_num, context, address, mnemonic, operands, size=size))
                    address += size
                    continue

                if mnemonic == "DB":
                    size = 0
                    for item in operands:
                        string = _STRING_RE.match(item)
                        if string:
                            length = len(_string_value(item))
                            if length == 0:
                                raise AssemblerError("Empty string in DB")
                            size += length
                        else:
                            size += 1
                    kind = "db"
                elif mnemonic == "DW":
                    size = 2 * len(operands)
                    kind = "dw"
                else:
                    size = INSTRUCTION_SIZES[mnemonic]
                    kind = "instr"

                if address + size > 0x10000:
                    raise AssemblerError(f"Program exceeds the 64KB address space at {address:04X}H")
                statements.append(_Statement(kind, line_num, context, address, mnemonic, operands, size=size))
                address += size

            except UndefinedSymbolError as e:
                raise SyntaxError(f"Line {line_num}{context}: {e}")
            except AssemblerError as e:
                raise SyntaxError(f"Line {line_num}{context}: {e}")

        if collecting is not None:
            what = collecting.get("name", collecting["kind"])
            raise SyntaxError(f"Line {collecting.get('line', 0)}: Missing ENDM for {what}")
        if conditions:
            raise SyntaxError(f"Line {conditions[-1][3]}: IF without ENDIF")
        return statements

    def _conditional(self, directive, operand_text, address, conditions, line_num):
        # Condition entries: [active, branch_taken, parent_active, line_num, else_seen]
        if directive == "IF":
            operands = _split_operands(operand_text)
            self._check_operand_count("IF", operands)
            value = self._evaluate(operands[0], address, allow_registers=True)
            condition = value != 0
            conditions.append([condition, condition, True, line_num, False])
        elif directive == "ELSE":
            if operand_text:
                raise AssemblerError("ELSE expects 0 operands")
            if not conditions:
                raise AssemblerError("ELSE without IF")
            entry = conditions[-1]
            if entry[4]:
                raise AssemblerError("Multiple ELSE for one IF")
            entry[4] = True
            entry[0] = entry[2] and not entry[1]
            entry[1] = True
        else:  # ENDIF
            if operand_text:
                raise AssemblerError("ENDIF expects 0 operands")
            if not conditions:
                raise AssemblerError("ENDIF without IF")
            conditions.pop()

    def _finish_block(self, block, conditions, stack):
        """Stores a macro definition or expands a REPT/IRP/IRPC block."""
        kind = block["kind"]
        if kind == "MACRO":
            self._macros[block["name"]] = _Macro(block["name"], block["params"], block["body"])
            return None

        line_num = block["line"]
        lines = []
        if kind == "REPT":
            for _ in range(block["count"]):
                lines.extend(self._substitute_body(block["body"], {}, line_num))
            name = "REPT"
        else:
            for value in block["values"]:
                lines.extend(self._substitute_body(block["body"], {block["param"]: value}, line_num))
            name = kind
        return _Frame(lines, "rept", name, len(conditions))

    def _expand_macro(self, macro, args, line_num, cond_depth):
        if len(args) > len(macro.params):
            raise AssemblerError(
                f"Macro {macro.name} expects at most {len(macro.params)} argument(s), got {len(args)}"
            )
        mapping = dict(zip(macro.params, args + [""] * (len(macro.params) - len(args))))
        lines = self._substitute_body(macro.body, mapping, line_num)
        return _Frame(lines, "macro", f"macro {macro.name}", cond_depth)

    def _substitute_body(self, body, mapping, line_num):
        """Applies parameter and LOCAL substitution to a block body."""
        mapping = dict(mapping)
        lines = []
        locals_allowed = True
        for code in body:
            words = code.split(None, 1)
            if locals_allowed and words and words[0] == "LOCAL":
                for local in _split_operands(words[1] if len(words) > 1 else ""):
                    if not _NAME_RE.fullmatch(local):
                        raise AssemblerError(f"Invalid LOCAL name: {local}")
                    self._local_counter += 1
                    mapping[local] = f"??{self._local_counter:04d}"
                continue
            locals_allowed = False
            lines.append((line_num, self._substitute(code, mapping) if mapping else code))
        return lines

    @staticmethod
    def _substitute(code, mapping):
        """Replaces whole-word parameters; '&' concatenates a parameter with adjacent text."""
        result = ""
        i = 0
        length = len(code)
        while i < length:
            ch = code[i]
            if ch == "'":  # strings: only &PARAM / PARAM& forms are substituted
                j = i + 1
                while j < length:
                    if code[j] == "'":
                        if j + 1 < length and code[j + 1] == "'":
                            j += 2
                            continue
                        break
                    j += 1
                segment = code[i : j + 1]

                def replace(match):
                    name = match.group(1) or match.group(2)
                    return mapping.get(name, match.group(0))

                result += re.sub(r"&(" + _NAME + r")&?|(" + _NAME + r")&", replace, segment)
                i = j + 1
                continue
            if ch.isdigit():
                j = i
                while j < length and (code[j].isalnum()):
                    j += 1
                result += code[i:j]
                i = j
                continue
            match = _NAME_RE.match(code, i)
            if match and match.start() == i:
                name = match.group(0)
                end = match.end()
                if name in mapping:
                    if result.endswith("&"):
                        result = result[:-1]
                    result += mapping[name]
                    if end < length and code[end] == "&":
                        end += 1
                else:
                    result += name
                i = end
                continue
            result += ch
            i += 1
        return result

    # ------------------------------------------------------------------
    # Pass 2: machine code generation
    # ------------------------------------------------------------------

    def _pass2(self, statements):
        output = self._output
        self._set_values = {}  # replay SET definitions in source order
        end_address = 0
        has_code = False

        for statement in statements:
            address = statement.address
            try:
                kind = statement.kind
                if kind == "set":
                    value = self._evaluate(statement.operands[0], address, allow_registers=True)
                    self._set_values[statement.name] = value
                    output.listing.append(
                        (statement.line_num, address, b"", "set", self._expanded_text(statement), value)
                    )
                    continue
                if kind == "end":
                    if statement.operands:
                        output.starting_address = self._evaluate(statement.operands[0], address)
                    continue

                output.line_to_address_map.setdefault(statement.line_num, address)

                if kind == "ds":
                    for offset in range(statement.size):
                        output.data_memory_range.add(address + offset)
                    end_address = address + statement.size
                    output.listing.append(
                        (statement.line_num, address, b"", "ds", self._expanded_text(statement), statement.size)
                    )
                    continue

                if kind == "instr":
                    data = self._encode(statement.mnemonic, statement.operands, address)
                    output.parsed_program.append((address, [statement.mnemonic] + list(statement.operands)))
                    output.address_to_line_map[address] = statement.line_num
                    target = output.program_memory_range
                    has_code = True
                elif kind == "db":
                    data = self._encode_db(statement.operands, address)
                    target = output.data_memory_range
                else:  # dw
                    data = []
                    for item in statement.operands:
                        value = self._evaluate(item, address)
                        data += [value & 0xFF, value >> 8]
                    target = output.data_memory_range

                for offset, byte in enumerate(data):
                    output.memory[address + offset] = byte
                    target.add(address + offset)
                end_address = address + len(data)
                output.listing.append(
                    (statement.line_num, address, bytes(data), kind, self._expanded_text(statement), None)
                )

            except AssemblerError as e:
                raise SyntaxError(f"Line {statement.line_num}{statement.context}: {e}")

        # Keep the final value of SET symbols visible to the UI
        for name, value in self._set_values.items():
            output.symbols.setdefault(name, value)
        if has_code:
            output.program_end_address = end_address

    @staticmethod
    def _expanded_text(statement):
        """Source text of a statement generated by a macro/REPT/IRP expansion, else None."""
        if not statement.context:
            return None
        text = statement.mnemonic or ""
        if statement.kind == "set":
            text = f"{statement.name} SET"
        if statement.operands:
            text += " " + ", ".join(statement.operands)
        return text

    def _encode_db(self, items, address):
        data = []
        for item in items:
            if _STRING_RE.match(item):
                for ch in _string_value(item):
                    if ord(ch) > 0xFF:
                        raise AssemblerError(f"Character out of range in string: {ch}")
                    data.append(ord(ch))
            else:
                data.append(self._byte_value(item, address))
        return data

    def _byte_value(self, text, address):
        value = self._evaluate(text, address)
        if value >> 8 not in (0x00, 0xFF):
            raise AssemblerError(f"Value out of 8-bit range: {text} = {value:04X}H")
        return value & 0xFF

    def _unsigned_byte(self, text, address):
        """Offset for LDHI/LDSI: the CPU adds it as an unsigned byte (0-255)."""
        value = self._evaluate(text, address)
        if value > 0xFF:
            raise AssemblerError(f"Offset must be 0-255 (added unsigned): {text} = {value:04X}H")
        return value

    def _encode(self, mnemonic, operands, address):
        """Returns the list of machine code bytes for one instruction."""

        def word(text):
            value = self._evaluate(text, address)
            return [value & 0xFF, value >> 8]

        if mnemonic in _NO_OPERAND_OPCODES:
            return [_NO_OPERAND_OPCODES[mnemonic]]

        if mnemonic in _ALU_REG_OPCODES:
            return [_ALU_REG_OPCODES[mnemonic] | self._register(operands[0], address)]

        if mnemonic in _ALU_IMM_OPCODES:
            return [_ALU_IMM_OPCODES[mnemonic], self._byte_value(operands[0], address)]

        if mnemonic in _BYTE_OPERAND_OPCODES:
            return [_BYTE_OPERAND_OPCODES[mnemonic], self._unsigned_byte(operands[0], address)]

        if mnemonic in _ADDRESS_OPCODES:
            return [_ADDRESS_OPCODES[mnemonic]] + word(operands[0])

        if mnemonic == "MOV":
            dest = self._register(operands[0], address)
            src = self._register(operands[1], address)
            if dest == 6 and src == 6:
                raise AssemblerError("MOV M,M is not a valid instruction (opcode 76H is HLT)")
            return [0x40 | (dest << 3) | src]

        if mnemonic == "MVI":
            return [0x06 | (self._register(operands[0], address) << 3), self._byte_value(operands[1], address)]

        if mnemonic == "LXI":
            return [0x01 | (self._register_pair(operands[0], address) << 4)] + word(operands[1])

        if mnemonic == "INR":
            return [0x04 | (self._register(operands[0], address) << 3)]

        if mnemonic == "DCR":
            return [0x05 | (self._register(operands[0], address) << 3)]

        if mnemonic == "INX":
            return [0x03 | (self._register_pair(operands[0], address) << 4)]

        if mnemonic == "DCX":
            return [0x0B | (self._register_pair(operands[0], address) << 4)]

        if mnemonic == "DAD":
            return [0x09 | (self._register_pair(operands[0], address) << 4)]

        if mnemonic in ("PUSH", "POP"):
            code = self._stack_pair(operands[0], mnemonic, address)
            return [(0xC5 if mnemonic == "PUSH" else 0xC1) | (code << 4)]

        if mnemonic in ("LDAX", "STAX"):
            code = self._bd_pair(operands[0], mnemonic, address)
            return [(0x0A if mnemonic == "LDAX" else 0x02) | (code << 4)]

        if mnemonic == "RST":
            number = self._evaluate(operands[0], address)
            if not 0 <= number <= 7:
                raise AssemblerError("RST requires a number from 0-7")
            return [0xC7 | (number << 3)]

        if mnemonic == "IN":
            return [0xDB, self._byte_value(operands[0], address)]

        if mnemonic == "OUT":
            return [0xD3, self._byte_value(operands[0], address)]

        raise AssemblerError(f"Unknown instruction: {mnemonic}")

    # Register operands: register names or expressions evaluating to register codes
    def _register_expression(self, text, address, error):
        try:
            return self._evaluate(text, address, allow_registers=True)
        except AssemblerError:
            raise AssemblerError(error)

    def _register(self, text, address):
        if text in REGISTERS:
            return REGISTERS.index(text)
        error = f"Invalid register: {text}"
        if text in REGISTER_VALUES:
            raise AssemblerError(error)
        value = self._register_expression(text, address, error)
        if not 0 <= value <= 7:
            raise AssemblerError(error)
        return value

    def _register_pair(self, text, address):
        if text in REGISTER_PAIRS:
            return REGISTER_PAIRS.index(text)
        error = f"Invalid register pair: {text}"
        if text in REGISTER_VALUES:
            raise AssemblerError(error)
        value = self._register_expression(text, address, error)
        if value not in (0, 2, 4, 6):
            raise AssemblerError(error)
        return value // 2

    def _stack_pair(self, text, mnemonic, address):
        codes = {"B": 0, "D": 1, "H": 2, "PSW": 3}
        error = f"{mnemonic} only supports B, D, H or PSW, not {text}"
        if text in codes:
            return codes[text]
        if text in REGISTER_VALUES:
            raise AssemblerError(error)
        value = self._register_expression(text, address, error)
        if value not in (0, 2, 4, 6):
            raise AssemblerError(error)
        return value // 2

    def _bd_pair(self, text, mnemonic, address):
        error = f"{mnemonic} only supports B or D register pairs"
        if text in ("B", "D"):
            return 0 if text == "B" else 1
        if text in REGISTER_VALUES:
            raise AssemblerError(error)
        value = self._register_expression(text, address, error)
        if value not in (0, 2):
            raise AssemblerError(error)
        return value // 2

    # Not used by the assembler; kept for callers of earlier versions
    def _get_reg_code(self, reg):
        if reg not in REGISTERS:
            raise ValueError(f"Invalid register: {reg}")
        return REGISTERS.index(reg)

    def _get_rp_code(self, reg_pair):
        if reg_pair not in REGISTER_PAIRS:
            raise ValueError(f"Invalid register pair: {reg_pair}")
        return REGISTER_PAIRS.index(reg_pair)


class _ExpressionParser:
    """Recursive-descent parser implementing Intel operator precedence."""

    MASK = 0xFFFF

    def __init__(self, assembler, tokens, address, allow_registers, text):
        self.assembler = assembler
        self.tokens = tokens
        self.position = 0
        self.address = address
        self.allow_registers = allow_registers
        self.text = text

    def parse(self):
        value = self.parse_or()
        if self.position != len(self.tokens):
            raise AssemblerError(f"Invalid expression: {self.text.strip()}")
        return value

    def peek(self):
        if self.position < len(self.tokens):
            return self.tokens[self.position]
        return (None, None)

    def accept(self, *operators):
        kind, value = self.peek()
        if kind == "op" and value in operators:
            self.position += 1
            return value
        return None

    def parse_or(self):
        value = self.parse_and()
        while True:
            operator = self.accept("OR", "XOR", "|", "^")
            if operator is None:
                return value
            right = self.parse_and()
            value = (value | right) if operator in ("OR", "|") else (value ^ right)

    def parse_and(self):
        value = self.parse_not()
        while self.accept("AND", "&"):
            value &= self.parse_not()
        return value

    def parse_not(self):
        if self.accept("NOT", "~"):
            return (~self.parse_not()) & self.MASK
        return self.parse_relational()

    def parse_relational(self):
        value = self.parse_additive()
        while True:
            operator = self.accept("EQ", "NE", "LT", "LE", "GT", "GE")
            if operator is None:
                return value
            right = self.parse_additive()
            result = {
                "EQ": value == right, "NE": value != right,
                "LT": value < right, "LE": value <= right,
                "GT": value > right, "GE": value >= right,
            }[operator]
            value = self.MASK if result else 0

    def parse_additive(self):
        operator = self.accept("+", "-")
        value = self.parse_multiplicative()
        if operator == "-":
            value = (-value) & self.MASK
        while True:
            operator = self.accept("+", "-")
            if operator is None:
                return value
            right = self.parse_multiplicative()
            value = (value + right if operator == "+" else value - right) & self.MASK

    def parse_multiplicative(self):
        value = self.parse_high_low()
        while True:
            operator = self.accept("*", "/", "MOD", "SHL", "SHR", "<<", ">>")
            if operator is None:
                return value
            right = self.parse_high_low()
            if operator == "*":
                value = (value * right) & self.MASK
            elif operator in ("/", "MOD"):
                if right == 0:
                    raise AssemblerError(f"Division by zero in: {self.text.strip()}")
                value = value // right if operator == "/" else value % right
            elif operator in ("SHL", "<<"):
                value = (value << right) & self.MASK if right < 16 else 0
            else:
                value = value >> right if right < 16 else 0

    def parse_high_low(self):
        operator = self.accept("HIGH", "LOW")
        if operator == "HIGH":
            return self.parse_high_low() >> 8
        if operator == "LOW":
            return self.parse_high_low() & 0xFF
        if self.accept("NUL"):
            # NUL is true when nothing follows it (an empty macro argument)
            empty = self.position == len(self.tokens)
            self.position = len(self.tokens)
            return self.MASK if empty else 0
        return self.parse_primary()

    def parse_primary(self):
        kind, value = self.peek()
        if kind is None:
            raise AssemblerError(f"Incomplete expression: {self.text.strip()}")
        self.position += 1
        if kind == "num":
            return value
        if kind == "str":
            if len(value) == 0 or len(value) > 2:
                raise AssemblerError(f"String constant must be 1 or 2 characters in an expression: '{value}'")
            codes = [ord(ch) for ch in value]
            if any(code > 0xFF for code in codes):
                raise AssemblerError(f"Character out of range: '{value}'")
            return codes[0] if len(codes) == 1 else (codes[0] << 8) | codes[1]
        if kind == "name":
            return self.assembler._lookup(value, self.allow_registers)
        # operators
        if value == "$":
            if self.address is None:  # EQU looked up before its own line was reached
                raise UndefinedSymbolError("$")
            return self.address
        if value == "(":
            inner = self.parse_or()
            if not self.accept(")"):
                raise AssemblerError(f"Missing ')' in: {self.text.strip()}")
            return inner
        if value in ("+", "-"):  # unary sign inside a term, e.g. 2*-3
            operand = self.parse_high_low()
            return (-operand) & self.MASK if value == "-" else operand
        if value in ("NOT", "~"):
            return (~self.parse_high_low()) & self.MASK
        raise AssemblerError(f"Invalid expression: {self.text.strip()}")
